/* "shape" על שדה facts = יותר מדי מזהים בפסקה (אחרת — מבנה שגוי): ההודעה חייבת להגיד זאת, אחרת הניסיון החוזר חוזר על אותה טעות */
const TOO_MANY_FACTS_HINT = `פסקה ציטטה יותר מדי עובדות: צטט לכל היותר ${MAX_CITED_FACTS} מזהים בפסקה, רק את החשובות ביותר`
/* number_not_in_facts: המספר עצמו מצוין (מספר אינו ציטוט של הטקסט שנפסל) — כך המודל יודע מה להסיר או לצטט */
const numberHint = (detail: string): string => `המספר ${detail} הופיע בפסקה אך אינו מופיע בעובדות שצוטטו בה: השתמש רק במספרים מהעובדות שצוטטו באותה פסקה, או נסח בלי מספר`
const LATIN_HINT = 'הופיעו מילים באנגלית: כתוב בעברית בלבד'
const hintOf = (v: Violation): string =>
  v.code === 'shape' && v.detail === 'facts' ? TOO_MANY_FACTS_HINT
    : v.code === 'language' && v.detail === 'latin' ? LATIN_HINT
    : v.code === 'number_not_in_facts' && /^\d+(\.\d+)?$/.test(v.detail) ? numberHint(v.detail)
      : VIOLATION_HINT[v.code]

/* ההודעה לניסיון השני: מה נפסל (בלי ציטוט הטקסט שנפסל) */
export function buildRetryNote(violations: Violation[]): string {
  const hints = [...new Set(violations.map(hintOf))]
  return `\n\nהניסוח הקודם נפסל בבדיקה אוטומטית מהסיבות הבאות:\n${hints.map((h) => `- ${h}`).join('\n')}\nכתוב מחדש את הסיכום, תקן את כל הנקודות האלה, והחזר JSON בלבד.`
}
