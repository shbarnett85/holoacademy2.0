function genderLine(input: SummaryInput): string {
  if (input.scope !== 'student') return 'כתוב בלשון רבים על התלמידים.'
  if (input.gender === 'male') return 'כתוב על התלמיד בלשון זכר.'
  if (input.gender === 'female') return 'כתוב על התלמידה בלשון נקבה.'
  return 'מגדר התלמיד/ה אינו ידוע: השתמש בניסוח ניטרלי, כלומר שמות עצם ("הרמה עלתה", "נצפתה ירידה") במקום פעלים שדורשים מגדר, ו"התלמיד/ה" רק כשצריך.'
}

export function buildSummaryPrompt(input: SummaryInput): { system: string; user: string } {
  const unit = input.sampleUnit === 'sessions' ? 'הדמיות' : 'תלמידים'
  const facts = JSON.stringify(input.facts.map((f) => ({ id: f.id, text: f.text })), null, 1)
  const lines = [
    `היקף הסיכום: ${SCOPE_LABEL[input.scope]}.`,
    input.audience === 'subject' ? 'הקורא/ת הוא/היא מורה מקצועי/ת: העובדות מתייחסות למקצוע שלו/שלה בלבד.' : 'הקורא/ת הוא/היא מחנך/ת או מנהל/ת עם גישה מלאה.',
    input.gradeLabel ? `שכבה: ${input.gradeLabel}.` : '',
    genderLine(input),
    `גודל המדגם: ${input.sampleSize} ${unit}.`,
    'צעדים מעשיים מותרים (בחר/י 1-2):',
    ...STEPS[input.scope].map((s) => `- ${s}`),
    'העובדות (JSON):',
    facts,
  ].filter((l) => l !== '')
  return { system: SYSTEM, user: lines.join('\n') }
}

