/* ההודעה לניסיון השני: מה נפסל (קודים בלבד, בלי ציטוט הטקסט שנפסל) */
export function buildRetryNote(violations: Violation[]): string {
  const codes = [...new Set(violations.map((v) => v.code))]
  return `\n\nהניסוח הקודם נפסל בבדיקה אוטומטית מהסיבות הבאות:\n${codes.map((c) => `- ${VIOLATION_HINT[c]}`).join('\n')}\nכתוב מחדש את הסיכום, תקן את כל הנקודות האלה, והחזר JSON בלבד.`
}
